import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source=await readFile(new URL('../api/aione-bridge.js',import.meta.url),'utf8');
const start=source.indexOf('function forwardHeaders(');
const end=source.indexOf('\n}',start)+2;
assert(start>=0 && end>start);
const forward=vm.runInNewContext(`(${source.slice(start,end)})`,{Headers});
const headers=forward({headers:{'x-aione-connector-token':'test-only','authorization':'Bearer employee-test','x-serverless-authorization':'attacker','cookie':'private-cookie','host':'untrusted'}},'platform-test');
assert.equal(headers.get('x-aione-connector-token'),'test-only');
assert.equal(headers.get('authorization'),'Bearer employee-test');
assert.equal(headers.get('x-serverless-authorization'),'Bearer platform-test');
assert.equal(headers.get('cookie'),null);
assert.equal(headers.get('host'),null);
assert.equal(forward({headers:{}},'platform-test').get('x-aione-connector-token'),null);
const sessionHeaders=forward({headers:{cookie:'unrelated=secret; __Host-aione-session=test-session',origin:'https://aione.miwa-happyhouse.com','x-aione-request':'1','x-aione-client-address':'attacker','x-aione-proxy':'attacker','x-vercel-forwarded-for':'192.0.2.1'}},'platform-test');
assert.equal(sessionHeaders.get('cookie'),'__Host-aione-session=test-session');
assert.equal(sessionHeaders.get('origin'),'https://aione.miwa-happyhouse.com');
assert.equal(sessionHeaders.get('x-aione-request'),'1');
assert.equal(sessionHeaders.get('x-aione-client-address'),'192.0.2.1');
assert.equal(sessionHeaders.get('x-aione-proxy'),'vercel-wif-v1');
assert.equal(forward({headers:{cookie:'__Host-aione-session=a; __Host-aione-session=b'}},'platform-test').get('cookie'),null);
console.log('Connector proxy: 12 cookie/CSRF/IP/header forwarding and isolation checks passed');
