import assert from 'node:assert/strict';
import { connectorTarget, assertContainerTarget } from '../backend/scripts/erp-connector-target.mjs';
assert.throws(() => connectorTarget({}), /sole production/);
assert.throws(() => connectorTarget({ AIONE_CONNECTOR_ENV: 'development' }), /sole production/);
assert.throws(() => connectorTarget({ AIONE_CONNECTOR_ENV: 'production' }), /approval/);
assert.throws(() => connectorTarget({ AIONE_CONNECTOR_ENV: 'unknown' }), /Unknown/);
const prod = connectorTarget({ AIONE_CONNECTOR_ENV: 'production', AIONE_PRODUCTION_CONNECTOR_APPROVED: '1' });
assert.equal(prod.site, 'miwa-dev.localhost');
assert.equal(prod.container, 'miwa-erp-dev-backend-1');
assert.equal(prod.testReceipts, false);
assert.throws(() => connectorTarget({ AIONE_CONNECTOR_ENV: 'production', AIONE_PRODUCTION_CONNECTOR_APPROVED: '1', AIONE_CLOUD_URL: 'http://127.0.0.1:5500' }), /origin/);
const inspection = { Config: { Labels: { 'com.docker.compose.project': prod.project, 'com.docker.compose.service': 'backend' } }, State: { Running: true } };
assertContainerTarget(prod, inspection);
assert.throws(() => assertContainerTarget(prod, { Config: { Labels: { 'com.docker.compose.project': 'miwa-erp-test', 'com.docker.compose.service': 'backend' } }, State: { Running: true } }), /identity/);
assert.throws(() => assertContainerTarget(prod, { ...inspection, State: { Running: false } }), /state/);
assert.throws(() => assertContainerTarget(prod, {}), /identity/);
console.log('PASS: connector environment, approval, origin and container isolation');
