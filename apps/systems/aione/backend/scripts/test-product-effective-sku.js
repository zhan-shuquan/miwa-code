import assert from 'node:assert/strict';
import {normalizeProductEntry,buildSkuEntries,exportProductEntries,parseProductEntryWorkbook} from '../src/services/product-entry-contract.js';
import {calculateProductCosts} from '../../js/config/product-shared-cost-engine.js';
import {INITIAL_PARAMETERS} from '../../js/config/shared-parameter-defaults.js';
const p=normalizeProductEntry({localCode:'zjl901',nameZh:'SKU契约测试',purchaseUnitCostCny:10,setQuantity:3,weightG:60,actualShipmentWeightG:200,domesticFreightCny:2,packagingMethod:'真空包装',sizeClass:'3cm厚',salePriceJpy:980,specs:[{name:'颜色',values:['黑色','白色']}],extraAttributes:{independentSkuPricing:'true'},skuOverrides:[{index:2,identity:'颜色=白色',priceJpy:1580,purchaseCostCny:20,purchaseCostBasis:'set',setQuantity:5,weightG:70,actualShipmentWeightG:380,domesticFreightCny:0,packagingMethod:'定制包装',customPackagingCostCny:3,sizeClass:'60cm',packagingMaterial:'60cm纸箱'}]});
const cost=row=>calculateProductCosts(p,row,INITIAL_PARAMETERS);
const [a,b]=buildSkuEntries(p);
assert.equal(a.priceJpy,980);assert.equal(b.priceJpy,1580);
assert.equal(cost(b).price,b.priceJpy,'profit uses the contract price');
assert.equal(cost(b).weight,380,'explicit SKU parcel weight wins');
assert.equal(cost(a).ledger[0][2][0][1],750,'unit price times three at FX25');
assert.equal(cost(b).ledger[0][2][0][1],500,'per-set price is never multiplied twice');
assert.equal(cost(b).ledger[0][2][1][1],0,'zero domestic freight overrides default');
assert.equal(cost(b).ledger[0][2][2][1],75,'packaging is per sales set');
assert.equal(cost(b).japan,530,'SKU packaging and delivery tier');
assert.equal(cost(b).sizeClass,'60cm','display uses effective tier');
const changed=buildSkuEntries({...p,purchaseUnitCostCny:12,salePriceJpy:1080});
assert.equal(changed[0].purchaseCostCny,12);assert.equal(changed[1].purchaseCostCny,20);
assert.equal(changed[0].priceJpy,1080);assert.equal(changed[1].priceJpy,1580);
for(const costs of [true,false])for(const prices of [true,false]){
 const rows=buildSkuEntries({...p,extraAttributes:{independentSkuCosts:String(costs),independentSkuPricing:String(prices)}});
 assert.equal(rows[1].priceJpy,prices?1580:980);
 assert.equal(rows[1].purchaseCostCny,costs?20:10);
}
assert.equal(p.skuOverrides[0].priceJpy,1580,'mode toggles retain stored data');
const reordered=buildSkuEntries({...p,specs:[{name:'颜色',values:['白色','黑色']}]});
assert.equal(reordered[0].priceJpy,1580,'reorder follows identity, not index');
const estimated=buildSkuEntries({...p,skuOverrides:[{index:2,identity:'颜色=白色',setQuantity:5}]})[1];
assert.equal(estimated.actualShipmentWeightG,null,'quantity change invalidates inherited parcel weight');
assert.equal(cost(estimated).weight,300);assert.equal(cost(estimated).estimated,true);
const cleared=buildSkuEntries({...p,skuOverrides:[{index:2,identity:'颜色=白色',purchaseCostCny:null,priceJpy:null}]})[1];
assert.equal(cleared.purchaseCostCny,10);assert.equal(cleared.priceJpy,980);
const zero=buildSkuEntries({...p,skuOverrides:[{index:2,identity:'颜色=白色',purchaseCostCny:0,priceJpy:0}]})[1];
assert.equal(zero.purchaseCostCny,0);assert.equal(zero.priceJpy,0);
const roundtrip=await parseProductEntryWorkbook(await exportProductEntries([p]),'sku-roundtrip.xlsx');
assert.deepEqual(buildSkuEntries(roundtrip.items[0]),buildSkuEntries(p),'Excel retains modes, pricing basis and every cost override');
for(const override of [{setQuantity:0},{setQuantity:1.5},{actualShipmentWeightG:0},{domesticFreightCny:-1},{purchaseCostBasis:'unknown'}])assert.throws(()=>normalizeProductEntry({...p,skuOverrides:[{index:1,...override}]}));
const invalidPrice=buildSkuEntries({...p,salePriceJpy:null,skuOverrides:[]})[0];
assert.equal(invalidPrice.priceJpy,null,'suggested prices never silently become confirmed prices');
console.log('PASS effective SKU: inheritance, identity reorder, independent modes, units, weight, zero, profit, Excel and validation');
