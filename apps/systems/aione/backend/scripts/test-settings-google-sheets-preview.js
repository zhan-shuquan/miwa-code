import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {previewMaterialRows,MATERIAL_HEADERS} from '../../js/config/settings-google-sheets-mapping.js';
import {addMaterialSystemCodeField} from '../../js/config/product-setting-catalogs.js';
const category={id:'product_material',productField:'material',fields:[{id:'name_ja',type:'text'},{id:'name_en',type:'text'},{id:'system_code',type:'text'}],rows:[]};
const material=[MATERIAL_HEADERS,['','棉','綿','Cotton','待确认','候选','MAT_COTTON']];
const untouched=previewMaterialRows(category,material);
assert.equal(untouched.rows.length,0,'unconfirmed sheet candidates must never be auto-imported');
assert.equal(untouched.pending.length,1);
assert.equal(untouched.errors.length,0);
const ready=previewMaterialRows(category,[MATERIAL_HEADERS,['','棉','綿','Cotton','启用','confirmed','MAT_COTTON'],['','ABS','ABS樹脂','ABS resin','停用','confirmed','MAT_ABS']]);
assert.deepEqual(ready.rows.map(r=>({name:r.name,enabled:r.enabled})),[{name:'棉',enabled:true},{name:'ABS',enabled:false}]);
assert.deepEqual(ready.rows[0].values,{name_ja:'綿',name_en:'Cotton',system_code:'MAT_COTTON'});
assert.equal(ready.summary.ready,2);
const duplicate=previewMaterialRows(category,[MATERIAL_HEADERS,['','棉','綿','Cotton','启用','', 'MAT_COTTON'],['','棉','綿','Cotton','启用']]);
assert.equal(duplicate.errors.length,1);
const forged=previewMaterialRows(category,[MATERIAL_HEADERS,['random-id','棉','綿','Cotton','启用','','MAT_COTTON']]);
assert.equal(forged.errors.length,1);
const old={...category,rows:[{id:'r_existing',name:'棉',businessValue:'棉',values:{name_ja:'旧',name_en:'Old'}}]};
const update=previewMaterialRows(old,[MATERIAL_HEADERS,['r_existing','棉','綿','Cotton','启用','','MAT_COTTON']]);
assert.equal(update.rows[0].id,'r_existing');
assert.equal(update.rows[0].mode,'更新');
assert.throws(()=>previewMaterialRows(category,[['wrong','columns']]),/表头/);
const badCode=previewMaterialRows(category,[MATERIAL_HEADERS,['','棉','綿','Cotton','启用','','COTTON']]);assert.equal(badCode.errors.length,1);
const dupCode=previewMaterialRows(category,[MATERIAL_HEADERS,['','棉','綿','Cotton','启用','','MAT_COTTON'],['','棉二','綿','Cotton','启用','','MAT_COTTON']]);assert.equal(dupCode.errors.length,1);
const renamedCode=previewMaterialRows({...category,rows:[{id:'r_old',name:'棉',businessValue:'棉',values:{system_code:'MAT_OLD'}}]},[MATERIAL_HEADERS,['r_old','棉','綿','Cotton','启用','','MAT_COTTON']]);assert.equal(renamedCode.errors.length,1);
const older={customSettings:{categories:[{id:'product_material',productField:'material',fields:[{id:'name_ja',type:'text',label:'日文名称',required:false},{id:'name_en',type:'text',label:'英文名称',required:false}],rows:[]}]}};
const upgraded=addMaterialSystemCodeField(older);
assert.equal(upgraded.categories[0].fields.at(-1).id,'system_code');
assert.equal(older.customSettings.categories[0].fields.length,2);
assert.throws(()=>previewMaterialRows({...category,productField:'brand'},material),/材质/);
const reader=readFileSync(new URL('../src/services/settings-google-sheets-reader.js',import.meta.url),'utf8');
assert.ok(reader.includes('A1:G501'));
const routes=readFileSync(new URL('../src/routes/shared-parameters.js',import.meta.url),'utf8');
const ui=readFileSync(new URL('../../js/pages/custom-settings-editor.js',import.meta.url),'utf8');
assert.ok(reader.includes('spreadsheets.readonly'));
assert.ok(routes.includes("'/shared-parameters/google-material-preview',requireWriteActor,requireSettingsEditor"));
assert.ok(ui.includes('从 Google 表格预览'));
assert.ok(ui.includes("if(name==='google-preview')"));
console.log('PASS: Google settings preview reads only, checks schema/permissions and skips unconfirmed materials');
