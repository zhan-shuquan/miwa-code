import assert from 'node:assert/strict';
import {parseSupplierCSV,csvRows} from '../src/services/selection-sku-csv.js';
import {specifications,confirmSpecifications} from '../src/services/selection-specifications.js';
const url='https://detail.1688.com/offer/123.html';
const header='商品标题,商品ID,SKU ID,SKU名称,SKU图片链接,原价（元）,计算价格（元）,库存\n';
const line='测试,123,100,蓝色+80X135CM常规款400g,https://example.com/a.jpg,14.35,,12\n';
const parsed=parseSupplierCSV(Buffer.from(header+line),url);
assert.equal(parsed.skus[0].referenceWeight,400);
assert.equal(parsed.skus[0].cost,undefined);
assert.equal(parsed.skus[0].supplierStock,12);
assert.equal(parseSupplierCSV(Buffer.from(header+line+line),url).skus.length,1);
assert.throws(()=>parseSupplierCSV(Buffer.from(header+line),url.replace('123','999')),/不一致/);
assert.deepEqual(csvRows('a,"b,c"\r\n1,"x""y"'),[['a','b,c'],['1','x"y']]);
const snapshot={itemAttributes:[{name:'Colour'},{name:'Size'}]};
const data={sourceUrl:url,has_variants:true,specificationAttributes:[{attribute:'Colour',sales:true},{attribute:'Size',sales:false}],fixedSpecifications:{Size:'80×135cm'},skuSourceFiles:[parsed.source],skus:parsed.skus.map(s=>({...s,spec:'蓝色 常规款',confirmed:true,attributeValues:{Colour:'蓝色'}}))};
assert.equal(specifications(data,snapshot,true).skus.length,1);
assert.throws(()=>specifications({...data,skus:data.skus.map(s=>({...s,attributeValues:{Colour:'?色'}}))},snapshot,true),/未修正/);
assert.throws(()=>specifications({...data,skus:data.skus.map(s=>({...s,confirmed:false}))},snapshot,true),/尚未人工确认/);
assert.throws(()=>specifications({...data,specificationAttributes:[{attribute:'另建颜色',sales:true}]},snapshot),/ERP/);
assert.equal(specifications({...data,has_variants:false,skus:[],specificationAttributes:[],skuSourceFiles:[]},snapshot,true).has_variants,false);
assert.equal(specifications({...data,skus:data.skus.map(s=>({...s,cost:0}))},snapshot,true).skus[0].cost,0);
const pending={...data,skus:data.skus.map(s=>({...s,confirmed:false,spec:''}))};
const confirmed=confirmSpecifications(pending,snapshot);
assert.equal(confirmed.skus[0].confirmed,true);
assert.equal(confirmed.skus[0].spec,'蓝色 / 80×135cm');
assert.equal(pending.skus[0].confirmed,false);
assert.deepEqual(confirmSpecifications({...pending,...confirmed},snapshot),confirmed);
const excluded={...pending.skus[0],code:'removed',origin:'manual',selected:false,attributeValues:{Colour:'?'},quantity:2};
assert.deepEqual(confirmSpecifications({...pending,skus:[...pending.skus,excluded]},snapshot).skus[1],specifications({...pending,skus:[excluded]},snapshot).skus[0]);
assert.throws(()=>confirmSpecifications({...pending,skus:[...pending.skus,{...pending.skus[0],code:'duplicate',supplierSkuId:'duplicate-supplier',origin:'manual'}]},snapshot),/组合重复/);
assert.throws(()=>confirmSpecifications({...pending,skus:pending.skus.map(s=>({...s,attributeValues:{Colour:'?色'}}))},snapshot),/未修正/);
const manual={...pending,skuSourceFiles:[],skus:[{...pending.skus[0],origin:'manual',supplierSkuId:'supplier-123',supplierImageUrl:'https://example.com/manual.jpg',cost:0,quantity:2}]};
const roundtrip=confirmSpecifications(manual,snapshot).skus[0];
assert.equal(roundtrip.supplierSkuId,'supplier-123');
assert.equal(roundtrip.supplierImageUrl,'https://example.com/manual.jpg');
assert.equal(roundtrip.cost,0);
assert.equal(roundtrip.quantity,2);
const ranged={...manual,skuSourceFiles:[parsed.source],custom_单个采购价:6.8,skus:[{...data.skus[0],confirmed:false}]};
assert.equal(confirmSpecifications(ranged,snapshot).skus[0].confirmed,true);
assert.throws(()=>confirmSpecifications({...manual,skus:[manual.skus[0],{...manual.skus[0],code:'other',attributeValues:{Colour:'白色'}}]},snapshot),/1688 SKU ID重复/);
assert.throws(()=>specifications({...manual,skus:[{...manual.skus[0],supplierImageUrl:'javascript:alert(1)'}]},snapshot),/HTTP/);
console.log('selection specifications: original and unified confirmation regression passed');
