import assert from "node:assert/strict";
import {INITIAL_PARAMETERS} from "./shared-parameter-defaults.js";
import {calculateProductCosts,effectiveSizeClass} from "./product-shared-cost-engine.js";
const params=structuredClone(INITIAL_PARAMETERS);
const p={logisticsMethod:"空运直发（特殊）",purchaseUnitCostCny:24,setQuantity:1,domesticFreightCny:0,packagingMethod:"真空包装",sizeClass:"60cm",packagingMaterial:"60cm纸箱",actualShipmentWeightG:155,salePriceJpy:1980,rates:{platform:10,coupon:0,points:0,ads:0,other:0},profitTargets:{productMargin:40,operationMargin:20}};
const q=calculateProductCosts(p,null,params);
assert.equal(q.status,"priced");
assert.equal(q.sizeClass,"直发");
assert.equal(q.ledger[0][0],"直发履约成本");
assert.equal(q.japan,0);
assert.equal(q.weight,155);
assert.equal(q.ledger[0][2].find(x=>x[0]==="中国包装成本")[1],50);
assert.equal(q.ledger[0][2].find(x=>x[0]==="国际物流成本")[1],1125);
assert.equal(q.estimated,false);
assert.equal(q.baseCost,q.warehouse+q.platform);
assert.equal(q.gross,1980-q.baseCost);
assert.equal(q.net,q.gross-q.operation);
assert.equal(q.targetPrice%100,80);
const regular=calculateProductCosts({...p,logisticsMethod:"空运直发（普货）"},null,params);
assert.equal(regular.status,"priced");
assert.equal(regular.ledger[0][2][3][1],875);
assert.equal(regular.japan,0);
const warehouse=calculateProductCosts({...p,logisticsMethod:"空运大件（特殊）",packagingMethod:"重新包装"},null,params);
assert.equal(warehouse.sizeClass,"60cm");
assert.equal(warehouse.ledger[0][0],"到日本仓成本");
assert.equal(warehouse.japan,530);
assert.equal(warehouse.ledger[0][2][2][1],25);
assert.equal(warehouse.ledger[0][2][3][1],97);
assert.equal(effectiveSizeClass({...p,sizeClass:"60cm"},warehouse.mode),"60cm");
assert.equal(calculateProductCosts({...p,actualShipmentWeightG:null,weightG:155},null,params).estimated,true);
assert.equal(calculateProductCosts({...p,actualShipmentWeightG:null,weightG:0},null,params).status,"unconfigured");
assert.equal(calculateProductCosts({...p,packagingMethod:"定制包装",customPackagingCostCny:null},null,params).status,"unconfigured");
assert.equal(calculateProductCosts({...p,packagingMethod:"定制包装",customPackagingCostCny:3},null,params).ledger[0][2][2][1],75);
assert.equal(calculateProductCosts({...p,packagingMethod:"原装"},null,params).ledger[0][2][2][1],0);
const updated=structuredClone(params);updated.commerce.logistics.air_direct_special.firstFeeCny=55;
assert.equal(calculateProductCosts(p,null,updated).ledger[0][2][3][1],1375);
const skuA=calculateProductCosts({...p,actualShipmentWeightG:0,weightG:155},{weight:155,cost:24,price:1980},params);
const skuB=calculateProductCosts({...p,actualShipmentWeightG:0,weightG:155},{weight:700,cost:24,price:1980},params);
assert.equal(skuA.ledger[0][2][3][1],1125);
assert.equal(skuB.ledger[0][2][3][1],1500);
assert.equal(calculateProductCosts({...p,logisticsMethod:"空运大件（普货）"},null,params).japan,530);
const measuredSku=calculateProductCosts({...p,weightG:155,actualShipmentWeightG:155},{weight:700,cost:24,price:1980},params);
assert.equal(measuredSku.estimated,true,"distinct SKU weight must be separately estimated");
assert.equal(measuredSku.ledger[0][2][3][1],1500);
const sharedFeeChanged=structuredClone(params);sharedFeeChanged.shop.platformFeeRate=12;
assert.equal(calculateProductCosts(p,null,sharedFeeChanged).platform,238);
assert.equal(calculateProductCosts({...p,purchaseUnitCostCny:null},null,params).status,"unconfigured");
assert.equal(calculateProductCosts({...p,setQuantity:0},null,params).status,"unconfigured");
assert.equal(calculateProductCosts({...p,packagingMethod:"无效包装"},null,params).status,"unconfigured");
for(const mode of Object.values(params.commerce.logistics)){
 const result=calculateProductCosts({...p,logisticsMethod:mode.name},null,params);
 assert.equal(result.status,"priced",mode.name);
 assert.equal(result.japan,mode.fulfillment==="direct"?0:530,mode.name);
}
assert.equal(calculateProductCosts(p,null,null).status,"unconfigured");
console.log("PASS P0 eight logistics modes, cost integrity, missing weight, SKU, parameters, and owner-approved packaging.");
